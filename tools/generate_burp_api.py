#!/usr/bin/env python3
"""Generate the clean-room `burp` compatibility interfaces from the verified API contract.

The contract in `tools/api-contract.json` was extracted from PortSwigger's published
Extender API Javadoc (see `tools/fetch_burp_api.py`). It contains method signatures,
constant names and constant values only -- no implementation and no proprietary code.

Usage:
    python3 tools/generate_burp_api.py
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONTRACT = ROOT / "tools" / "api-contract.json"
OUT_DIR = ROOT / "src" / "main" / "java" / "burp"

HEADER = """// Blurp Suite - clean-room Burp Extender API compatibility layer.
// Generated by tools/generate_burp_api.py from tools/api-contract.json.
// Source of signatures/constants: PortSwigger's published Extender API Javadoc.
// Do not edit by hand; edit the contract or the generator instead.
package burp;

"""


def javadoc(text: str, indent: str = "") -> str:
    if not text:
        return ""
    clean = text.replace("*/", "* /").replace("\r", " ").strip()
    lines = [clean[i : i + 96] for i in range(0, len(clean), 96)] or [clean]
    body = "\n".join(f"{indent} * {line}" for line in lines)
    return f"{indent}/**\n{body}\n{indent} */\n"


def generate() -> int:
    contract = json.loads(CONTRACT.read_text(encoding="utf-8"))
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    count = 0

    for name, data in sorted(contract.items()):
        supers = data.get("extends") or []
        extends = f" extends {', '.join(supers)}" if supers else ""
        parts = [HEADER, javadoc(f"Compatibility interface for {name}."),
                 f"public interface {name}{extends} {{\n"]

        for field in data.get("fields") or []:
            value = field.get("value")
            if value is None:
                # Interface constants require a compile-time initializer.
                raise RuntimeError(f"Missing constant value for {name}.{field['name']}")
            field_type = field.get("type", "int")
            parts.append(f"    {field_type} {field['name']} = {value};\n")

        for method in data.get("methods") or []:
            parts.append("\n")
            parts.append(javadoc(method.get("description", ""), "    "))
            parts.append(f"    {method['signature']};\n")

        parts.append("}\n")
        (OUT_DIR / f"{name}.java").write_text("".join(parts), encoding="utf-8")
        count += 1

    return count


if __name__ == "__main__":
    written = generate()
    print(f"Generated {written} interfaces in {OUT_DIR}")
